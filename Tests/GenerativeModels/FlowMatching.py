"""
Flow matching for images
===========================

This script trains a generative model for images of handwritten digits with flow matching. Flow matching is
closely related to diffusion models: both turn random noise into data step by step. Flow matching learns a
velocity field that moves noise along straight lines towards the data, and new images are generated by following
this velocity field from pure noise.

The images are the 8 x 8 digits of scikit-learn, and the velocity field is a small dense network, so the model
trains in about a minute on a CPU. The model is conditioned on the digit, so it can be asked to draw a specific
digit.
"""
import torch
import matplotlib.pyplot as plt
from sklearn.datasets import load_digits

from DLL.DeepLearning.Model import Model
from DLL.DeepLearning.Layers import Dense
from DLL.DeepLearning.Layers.Activations import ReLU
from DLL.DeepLearning.Optimisers import ADAM
from DLL.DeepLearning.Losses import MSE


torch.manual_seed(0)

# %%
# Data
# ----
#
# The 1797 images are scaled to [-1, 1] and flattened to vectors of 64 pixels. The labels are one-hot encoded.

digits = load_digits()
images = torch.tensor(digits.data, dtype=torch.float32) / 8 - 1
labels = torch.eye(10)[torch.tensor(digits.target)]
n_pixels = images.shape[1]

# %%
# Flow matching
# -------------
#
# A training sample :math:`x_1` is paired with random noise :math:`x_0 \sim N(0, I)` and a random time
# :math:`t \sim U(0, 1)`. The point :math:`x_t = (1 - t)x_0 + tx_1` lies on the straight line from the noise to
# the image, and the velocity along this line is :math:`x_1 - x_0`. The network :math:`v(x_t, t, y)` learns to
# predict this velocity by minimising the mean squared error
#
# .. math::
#
#     L = E\|v(x_t, t, y) - (x_1 - x_0)\|^2.
#
# The time is given to the network as sine and cosine features, and the digit :math:`y` as a one-hot vector.

n_frequencies = 6


def time_features(t):
    frequencies = torch.pi * torch.arange(1, n_frequencies + 1)
    return torch.cat([t, torch.sin(t * frequencies), torch.cos(t * frequencies)], dim=1)


def network_input(x, t, y):
    return torch.cat([x, time_features(t), y], dim=1)


model = Model(n_pixels + 1 + 2 * n_frequencies + 10)
model.add(Dense(256, activation=ReLU()))
model.add(Dense(256, activation=ReLU()))
model.add(Dense(256, activation=ReLU()))
model.add(Dense(n_pixels))
model.compile(optimiser=ADAM(learning_rate=0.001), loss=MSE())
model.summary()

# %%
# Training
# --------
#
# Every step draws a new batch of images, noise and times, so the training loop is written by hand: predict the
# velocity, compute the gradient of the loss and backpropagate it through the network.

n_steps = 6000
batch_size = 128
losses = []
model.train()
for step in range(n_steps):
    indices = torch.randint(0, len(images), (batch_size,))
    x1, y = images[indices], labels[indices]
    x0 = torch.randn_like(x1)
    t = torch.rand(batch_size, 1)
    xt = (1 - t) * x0 + t * x1
    target = x1 - x0

    model.optimiser.zero_grad()
    velocity = model.predict(network_input(xt, t, y))
    model.backward(model.loss.gradient(velocity, target))
    model.optimiser.update_parameters()
    losses.append(model.loss.loss(velocity, target).item())
    if (step + 1) % 1000 == 0:
        print(f"Step {step + 1}: loss {sum(losses[-1000:]) / 1000:.4f}")
model.eval()

plt.figure(figsize=(8, 4))
plt.plot(torch.tensor(losses).reshape(-1, 50).mean(dim=1))
plt.xlabel("Training step / 50")
plt.ylabel("Mean squared error")
plt.title("Flow matching loss")
plt.grid(alpha=0.3)
plt.tight_layout()

# %%
# Generating digits
# -----------------
#
# New images are generated by starting from noise at :math:`t = 0` and following the learned velocity field with
# 40 Euler steps until :math:`t = 1`. Every row below is generated from different noise for the digit on its left.


def generate(y, n_steps=40, return_path=False):
    x = torch.randn(len(y), n_pixels)
    path = [x]
    for i in range(n_steps):
        t = torch.full((len(y), 1), i / n_steps)
        x = x + model.predict(network_input(x, t, y)) / n_steps
        path.append(x)
    return path if return_path else x


n_per_digit = 10
y = torch.eye(10).repeat_interleave(n_per_digit, dim=0)
samples = generate(y).clamp(-1, 1)

fig, axes = plt.subplots(10, n_per_digit, figsize=(n_per_digit, 10))
for i, ax in enumerate(axes.ravel()):
    ax.imshow(samples[i].reshape(8, 8), cmap="gray_r", vmin=-1, vmax=1)
    ax.set_xticks([])
    ax.set_yticks([])
for digit in range(10):
    axes[digit, 0].set_ylabel(str(digit), rotation=0, labelpad=12, fontsize=12)
fig.suptitle("Generated digits")
plt.tight_layout()

# %%
# From noise to an image
# ----------------------
#
# The path of one sample of every digit from pure noise (left) to the final image (right).

path = generate(torch.eye(10), return_path=True)
shown_steps = [0, 8, 16, 24, 32, 40]
fig, axes = plt.subplots(10, len(shown_steps), figsize=(len(shown_steps), 10))
for row in range(10):
    for column, step in enumerate(shown_steps):
        axes[row, column].imshow(path[step][row].clamp(-1, 1).reshape(8, 8), cmap="gray_r", vmin=-1, vmax=1)
        axes[row, column].set_xticks([])
        axes[row, column].set_yticks([])
for column, step in enumerate(shown_steps):
    axes[0, column].set_title(f"t = {step / 40:.1f}")
for digit in range(10):
    axes[digit, 0].set_ylabel(str(digit), rotation=0, labelpad=12, fontsize=12)
plt.tight_layout()
plt.show()
