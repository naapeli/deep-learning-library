"""
Variational autoencoder
==========================

This script trains a variational autoencoder (VAE) on the 8 x 8 digits of scikit-learn. The encoder compresses
every image into a distribution over a two-dimensional latent space, and the decoder turns points of the latent
space back into images. Because the latent space is two-dimensional, it can be plotted directly, and new digits
are generated by decoding points of it.

The encoder and the decoder are two separate :class:`~DLL.DeepLearning.Model.Model` objects, which are trained
together with a custom training loop. At the end, a conditional VAE is trained, which also gets the digit as an
input and can therefore generate a chosen digit.
"""
import torch
import matplotlib.pyplot as plt
from sklearn.datasets import load_digits

from DLL.DeepLearning.Model import Model
from DLL.DeepLearning.Layers import Dense
from DLL.DeepLearning.Layers.Activations import ReLU, Sigmoid
from DLL.DeepLearning.Optimisers import ADAM


torch.manual_seed(0)

# %%
# Data
# ----
#
# The pixels are scaled to [0, 1], so that every pixel can be modelled as the probability of the pixel being
# dark.

digits = load_digits()
images = torch.tensor(digits.data, dtype=torch.float32) / 16
targets = torch.tensor(digits.target)
n_pixels = images.shape[1]
latent_dim = 2

# %%
# The models
# ----------
#
# The encoder outputs the mean :math:`\mu` and the logarithm of the variance :math:`\log\sigma^2` of a normal
# distribution in the latent space. The decoder maps a latent point to the pixel probabilities with a sigmoid.

encoder = Model(n_pixels)
encoder.add(Dense(256, activation=ReLU()))
encoder.add(Dense(128, activation=ReLU()))
encoder.add(Dense(2 * latent_dim))
encoder.compile(optimiser=ADAM(learning_rate=0.001))

decoder = Model(latent_dim)
decoder.add(Dense(128, activation=ReLU()))
decoder.add(Dense(256, activation=ReLU()))
decoder.add(Dense(n_pixels, activation=Sigmoid()))
decoder.compile(optimiser=ADAM(learning_rate=0.001))

# %%
# Training
# --------
#
# A latent point is sampled with the reparameterisation trick :math:`z = \mu + \sigma\epsilon`, where
# :math:`\epsilon \sim N(0, I)`, so that the gradient can flow through the sampling into the encoder. The loss of
# an image is the reconstruction error (the binary cross entropy summed over the pixels) plus the
# Kullback-Leibler divergence between the encoder's distribution and the standard normal prior,
#
# .. math::
#
#     L = -\sum_j \left(x_j\log\hat{x}_j + (1 - x_j)\log(1 - \hat{x}_j)\right) - \frac{1}{2}\sum_k\left(1 + \log\sigma_k^2 - \mu_k^2 - \sigma_k^2\right).
#
# The gradients are written out by hand: the decoder returns the gradient with respect to its input :math:`z`,
# which is propagated through the sampling step and combined with the gradient of the KL divergence.

n_epochs = 300
batch_size = 128
eps = 1e-6
history = {"reconstruction": [], "kl": []}
encoder.train()
decoder.train()
for epoch in range(n_epochs):
    reconstruction_total, kl_total = 0, 0
    for batch in torch.randperm(len(images)).split(batch_size):
        x = images[batch]
        n = len(x)
        encoder.optimiser.zero_grad()
        decoder.optimiser.zero_grad()

        mean, log_var = encoder.predict(x).chunk(2, dim=1)
        std = torch.exp(0.5 * log_var)
        noise = torch.randn_like(std)
        z = mean + std * noise
        x_hat = decoder.predict(z).clamp(eps, 1 - eps)

        reconstruction = -(x * torch.log(x_hat) + (1 - x) * torch.log(1 - x_hat)).sum() / n
        kl = -0.5 * (1 + log_var - mean ** 2 - log_var.exp()).sum() / n
        reconstruction_total += reconstruction.item() * n
        kl_total += kl.item() * n

        # gradient of the loss (averaged over the batch) with respect to the decoder output
        dL_dxhat = (x_hat - x) / (x_hat * (1 - x_hat)) / n
        dL_dz = decoder.backward(dL_dxhat)
        dL_dmean = dL_dz + mean / n
        dL_dlog_var = dL_dz * 0.5 * std * noise + 0.5 * (log_var.exp() - 1) / n
        encoder.backward(torch.cat([dL_dmean, dL_dlog_var], dim=1))

        encoder.optimiser.update_parameters()
        decoder.optimiser.update_parameters()

    history["reconstruction"].append(reconstruction_total / len(images))
    history["kl"].append(kl_total / len(images))
    if (epoch + 1) % 50 == 0:
        print(f"Epoch {epoch + 1}: reconstruction {history['reconstruction'][-1]:.2f}, KL divergence {history['kl'][-1]:.2f}")
encoder.eval()
decoder.eval()

fig, ax = plt.subplots(1, 2, figsize=(10, 4))
ax[0].plot(history["reconstruction"])
ax[0].set_title("Reconstruction error")
ax[1].plot(history["kl"])
ax[1].set_title("KL divergence")
for a in ax:
    a.set_xlabel("Epoch")
    a.grid(alpha=0.3)
plt.tight_layout()

# %%
# Reconstructions
# ---------------
#
# Original images (top) and their reconstructions from the mean of the latent distribution (bottom). Squeezing
# an image through only two numbers loses details, but keeps the identity of most digits.

examples = images[:12]
reconstructions = decoder.predict(encoder.predict(examples)[:, :latent_dim])
fig, axes = plt.subplots(2, 12, figsize=(12, 2.4))
for i in range(12):
    axes[0, i].imshow(examples[i].reshape(8, 8), cmap="gray_r", vmin=0, vmax=1)
    axes[1, i].imshow(reconstructions[i].reshape(8, 8), cmap="gray_r", vmin=0, vmax=1)
for ax in axes.ravel():
    ax.set_xticks([])
    ax.set_yticks([])
axes[0, 0].set_ylabel("Original")
axes[1, 0].set_ylabel("Decoded")
plt.tight_layout()

# %%
# The latent space
# ----------------
#
# The latent means of all images, coloured by the digit. The model has not seen the labels, but similar digits
# end up close to each other. Below, a grid of latent points is decoded into images, which shows how the digits
# change smoothly across the latent space.

latent_means = encoder.predict(images)[:, :latent_dim]
plt.figure(figsize=(7, 6))
scatter = plt.scatter(latent_means[:, 0], latent_means[:, 1], c=targets, cmap="tab10", s=8)
plt.legend(*scatter.legend_elements(), title="Digit", loc="upper right", fontsize=8)
plt.xlim(-3, 3)
plt.ylim(-3, 3)
plt.xlabel("$z_1$")
plt.ylabel("$z_2$")
plt.title("Latent means of the images")
plt.tight_layout()

grid_size = 10
grid = torch.linspace(-2.5, 2.5, grid_size)
fig, axes = plt.subplots(grid_size, grid_size, figsize=(8, 8))
for row in range(grid_size):
    for column in range(grid_size):
        z = torch.tensor([[grid[column], grid[grid_size - 1 - row]]])
        axes[row, column].imshow(decoder.predict(z).reshape(8, 8), cmap="gray_r", vmin=0, vmax=1)
        axes[row, column].set_xticks([])
        axes[row, column].set_yticks([])
for i in range(grid_size):
    axes[grid_size - 1, i].set_xlabel(f"{grid[i]:.1f}", fontsize=8)
    axes[grid_size - 1 - i, 0].set_ylabel(f"{grid[i]:.1f}", fontsize=8, rotation=0, labelpad=14)
fig.supxlabel("$z_1$")
fig.supylabel("$z_2$")
fig.suptitle("Decoded latent points")
plt.tight_layout()

# %%
# Generating new digits
# ---------------------
#
# New digits are generated by sampling latent points from the standard normal prior and decoding them.

samples = decoder.predict(torch.randn(40, latent_dim))
fig, axes = plt.subplots(4, 10, figsize=(10, 4))
for sample, ax in zip(samples, axes.ravel()):
    ax.imshow(sample.reshape(8, 8), cmap="gray_r", vmin=0, vmax=1)
    ax.set_xticks([])
    ax.set_yticks([])
plt.tight_layout()

# %%
# Conditional variational autoencoder
# -----------------------------------
#
# A conditional VAE gives the label of the image to both the encoder and the decoder as a one-hot vector. The
# decoder then knows which digit to draw, so the latent space only has to describe the rest: the style of the
# handwriting, such as the thickness and the slant. The training is the same as above; only the inputs of the
# networks change.

one_hot_labels = torch.eye(10)[targets]

conditional_encoder = Model(n_pixels + 10)
conditional_encoder.add(Dense(256, activation=ReLU()))
conditional_encoder.add(Dense(128, activation=ReLU()))
conditional_encoder.add(Dense(2 * latent_dim))
conditional_encoder.compile(optimiser=ADAM(learning_rate=0.001))

conditional_decoder = Model(latent_dim + 10)
conditional_decoder.add(Dense(128, activation=ReLU()))
conditional_decoder.add(Dense(256, activation=ReLU()))
conditional_decoder.add(Dense(n_pixels, activation=Sigmoid()))
conditional_decoder.compile(optimiser=ADAM(learning_rate=0.001))

conditional_encoder.train()
conditional_decoder.train()
for epoch in range(n_epochs):
    reconstruction_total = 0
    for batch in torch.randperm(len(images)).split(batch_size):
        x, y = images[batch], one_hot_labels[batch]
        n = len(x)
        conditional_encoder.optimiser.zero_grad()
        conditional_decoder.optimiser.zero_grad()

        mean, log_var = conditional_encoder.predict(torch.cat([x, y], dim=1)).chunk(2, dim=1)
        std = torch.exp(0.5 * log_var)
        noise = torch.randn_like(std)
        z = mean + std * noise
        x_hat = conditional_decoder.predict(torch.cat([z, y], dim=1)).clamp(eps, 1 - eps)
        reconstruction_total += -(x * torch.log(x_hat) + (1 - x) * torch.log(1 - x_hat)).sum().item()

        # the decoder returns the gradient with respect to its whole input; the first columns belong to z
        dL_dz = conditional_decoder.backward((x_hat - x) / (x_hat * (1 - x_hat)) / n)[:, :latent_dim]
        dL_dmean = dL_dz + mean / n
        dL_dlog_var = dL_dz * 0.5 * std * noise + 0.5 * (log_var.exp() - 1) / n
        conditional_encoder.backward(torch.cat([dL_dmean, dL_dlog_var], dim=1))

        conditional_encoder.optimiser.update_parameters()
        conditional_decoder.optimiser.update_parameters()
    if (epoch + 1) % 50 == 0:
        print(f"Conditional VAE, epoch {epoch + 1}: reconstruction {reconstruction_total / len(images):.2f}")
conditional_encoder.eval()
conditional_decoder.eval()

# %%
# Every column below decodes the same latent point with each of the ten labels. Because the latent point
# describes the style and the label the digit, the digits in a column are written in a similar style.

n_styles = 8
styles = torch.randn(n_styles, latent_dim)
fig, axes = plt.subplots(10, n_styles, figsize=(n_styles, 10))
for digit in range(10):
    y = torch.eye(10)[digit].expand(n_styles, 10)
    generated = conditional_decoder.predict(torch.cat([styles, y], dim=1))
    for column in range(n_styles):
        axes[digit, column].imshow(generated[column].reshape(8, 8), cmap="gray_r", vmin=0, vmax=1)
        axes[digit, column].set_xticks([])
        axes[digit, column].set_yticks([])
    axes[digit, 0].set_ylabel(str(digit), rotation=0, labelpad=12, fontsize=12)
for column in range(n_styles):
    axes[0, column].set_title(f"style {column + 1}", fontsize=9)
plt.tight_layout()
plt.show()
