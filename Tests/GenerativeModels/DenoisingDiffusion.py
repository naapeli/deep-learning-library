"""
Denoising diffusion probabilistic model
==========================================

This script trains a denoising diffusion probabilistic model (DDPM) for the 8 x 8 digits of scikit-learn. A fixed
forward process destroys an image by adding a little Gaussian noise at each of 200 steps, until only noise is
left. A network learns to predict the noise that was added, and new images are generated by starting from pure
noise and removing the predicted noise step by step.

The setup is the same as in the flow matching example: the network is a small dense network conditioned on the
digit. Flow matching moves along straight lines from noise to data, while a DDPM follows a noisy path defined by
the noise schedule.
"""
import torch
import matplotlib.pyplot as plt
from sklearn.datasets import load_digits

from DLL.DeepLearning.Model import Model
from DLL.DeepLearning.Layers import Dense
from DLL.DeepLearning.Layers.Activations import ReLU
from DLL.DeepLearning.Optimisers import ADAM
from DLL.DeepLearning.Losses import MSE


torch.manual_seed(0)

# %%
# Data
# ----

digits = load_digits()
images = torch.tensor(digits.data, dtype=torch.float32) / 8 - 1
labels = torch.eye(10)[torch.tensor(digits.target)]
n_pixels = images.shape[1]

# %%
# The forward process
# -------------------
#
# At step :math:`t`, the image is scaled down and noise with variance :math:`\beta_t` is added. The variances grow
# linearly from :math:`10^{-4}` to :math:`0.04` over :math:`T = 200` steps. With
# :math:`\bar\alpha_t = \prod_{s \leq t}(1 - \beta_s)`, the noisy image at any step can be sampled directly as
#
# .. math::
#
#     x_t = \sqrt{\bar\alpha_t}x_0 + \sqrt{1 - \bar\alpha_t}\epsilon, \quad \epsilon \sim N(0, I).

T = 200
betas = torch.linspace(1e-4, 0.04, T)
alphas = 1 - betas
alpha_bars = torch.cumprod(alphas, dim=0)


def add_noise(x0, t, noise):
    return alpha_bars[t].sqrt().unsqueeze(1) * x0 + (1 - alpha_bars[t]).sqrt().unsqueeze(1) * noise


shown_steps = [0, 20, 50, 100, 150, 199]
fig, axes = plt.subplots(1, len(shown_steps), figsize=(len(shown_steps) * 1.5, 1.8))
for ax, t in zip(axes, shown_steps):
    noisy = add_noise(images[:1], torch.tensor([t]), torch.randn(1, n_pixels))
    ax.imshow(noisy.reshape(8, 8).clamp(-1, 1), cmap="gray_r", vmin=-1, vmax=1)
    ax.set_title(f"t = {t + 1}")
    ax.axis("off")
plt.tight_layout()

# %%
# The noise prediction network
# ----------------------------
#
# The network :math:`\epsilon_\theta(x_t, t, y)` gets the noisy image, the step as sine and cosine features and the
# digit :math:`y` as a one-hot vector, and predicts the added noise. It is trained with the mean squared error
# :math:`E\|\epsilon_\theta(x_t, t, y) - \epsilon\|^2` on random images, steps and noise.

n_frequencies = 6


def network_input(x, t, y):
    s = (t.float() / T).unsqueeze(1)
    frequencies = torch.pi * torch.arange(1, n_frequencies + 1)
    return torch.cat([x, s, torch.sin(s * frequencies), torch.cos(s * frequencies), y], dim=1)


model = Model(n_pixels + 1 + 2 * n_frequencies + 10)
model.add(Dense(256, activation=ReLU()))
model.add(Dense(256, activation=ReLU()))
model.add(Dense(256, activation=ReLU()))
model.add(Dense(n_pixels))
model.compile(optimiser=ADAM(learning_rate=0.001), loss=MSE())

n_steps = 6000
batch_size = 128
losses = []
model.train()
for step in range(n_steps):
    indices = torch.randint(0, len(images), (batch_size,))
    x0, y = images[indices], labels[indices]
    t = torch.randint(0, T, (batch_size,))
    noise = torch.randn_like(x0)

    model.optimiser.zero_grad()
    predicted_noise = model.predict(network_input(add_noise(x0, t, noise), t, y))
    model.backward(model.loss.gradient(predicted_noise, noise))
    model.optimiser.update_parameters()
    losses.append(model.loss.loss(predicted_noise, noise).item())
    if (step + 1) % 1000 == 0:
        print(f"Step {step + 1}: loss {sum(losses[-1000:]) / 1000:.4f}")
model.eval()

plt.figure(figsize=(8, 4))
plt.plot(torch.tensor(losses).reshape(-1, 50).mean(dim=1))
plt.xlabel("Training step / 50")
plt.ylabel("Mean squared error of the noise")
plt.grid(alpha=0.3)
plt.tight_layout()

# %%
# Generating digits
# -----------------
#
# Sampling starts from pure noise :math:`x_T` and applies the learned reverse step for :math:`t = T, \dots, 1`,
#
# .. math::
#
#     x_{t - 1} = \frac{1}{\sqrt{1 - \beta_t}}\left(x_t - \frac{\beta_t}{\sqrt{1 - \bar\alpha_t}}\epsilon_\theta(x_t, t, y)\right) + \sqrt{\beta_t}z, \quad z \sim N(0, I),
#
# where no noise is added in the last step. Every row is generated for the digit on its left.


def generate(y, return_path=False):
    x = torch.randn(len(y), n_pixels)
    path = [x]
    for t in reversed(range(T)):
        steps = torch.full((len(y),), t)
        predicted_noise = model.predict(network_input(x, steps, y))
        x = (x - betas[t] / (1 - alpha_bars[t]).sqrt() * predicted_noise) / alphas[t].sqrt()
        if t > 0:
            x = x + betas[t].sqrt() * torch.randn_like(x)
        path.append(x)
    return path if return_path else x


n_per_digit = 10
samples = generate(torch.eye(10).repeat_interleave(n_per_digit, dim=0)).clamp(-1, 1)
fig, axes = plt.subplots(10, n_per_digit, figsize=(n_per_digit, 10))
for i, ax in enumerate(axes.ravel()):
    ax.imshow(samples[i].reshape(8, 8), cmap="gray_r", vmin=-1, vmax=1)
    ax.set_xticks([])
    ax.set_yticks([])
for digit in range(10):
    axes[digit, 0].set_ylabel(str(digit), rotation=0, labelpad=12, fontsize=12)
fig.suptitle("Generated digits")
plt.tight_layout()

# %%
# From noise to an image
# ----------------------
#
# The reverse process for one sample of every digit. Most of the structure appears during the last steps, where
# the noise level is low.

path = generate(torch.eye(10), return_path=True)
shown = [0, 100, 150, 180, 190, 200]
fig, axes = plt.subplots(10, len(shown), figsize=(len(shown), 10))
for row in range(10):
    for column, index in enumerate(shown):
        axes[row, column].imshow(path[index][row].clamp(-1, 1).reshape(8, 8), cmap="gray_r", vmin=-1, vmax=1)
        axes[row, column].set_xticks([])
        axes[row, column].set_yticks([])
    axes[row, 0].set_ylabel(str(row), rotation=0, labelpad=12, fontsize=12)
for column, index in enumerate(shown):
    axes[0, column].set_title(f"t = {T - index}")
plt.tight_layout()
plt.show()
